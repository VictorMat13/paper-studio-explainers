import React from "react";
import { AbsoluteFill, Audio, Sequence, staticFile } from "remotion";
import { CrtPass } from "./kit";
import { PadCtx } from "../paperstudio";
import { HookOverlay } from "./overlay";
import { bodyOf, GroupStartCtx, hookOf, TIMELINE, VariantCtx, type GroupId, type Variant } from "./timing";
import { HA } from "./beats/HA";
import { HB } from "./beats/HB";
import { HC } from "./beats/HC";
import { BodyA } from "./beats/BodyA";
import { BodyB } from "./beats/BodyB";
import { BodyC } from "./beats/BodyC";

// ===========================================================================
// GithubEp08: Made By AI ep08 "What GitHub actually is" (Paper Studio), 1080x1920 @ 30 fps.
// Three hooks and three bodies, every hook with every body from day one, hook letter first:
//   hooks:  HA (H1 the reel's hook kept close), HB (H2 fear of loss), HC (H3 the words)
//   bodies: BodyA (what it actually is), BodyB (the routine), BodyC (what goes wrong without it)
//   "A" = HA + BodyA, "B" = HB + BodyB, "C" = HC + BodyC,
//   "AB" = HA + BodyB, "AC" = HA + BodyC, "BA" = HB + BodyA, "BC" = HB + BodyC, "CA" = HC + BodyA, "CB" = HC + BodyB
//   "<v>YT" = the YouTube Shorts cut of <v> (the CTA shot says "Subscribe to learn more about AI.", no keyword).
// A variant's two groups are H<hookOf(v)> then Body<bodyOf(v)>: the same six components in all 18 videos.
// Duration and every shot frame come from timeline.ts (generated by ep08 github/tools/make_ep08_timeline.py from
// the storyboard, then from the voice's word timings).
//
// The shell owns: the voiceover, ONE CrtPass over the whole finished frame (beats must not add their own), the 5%
// side padding (PadCtx 0.9), the two beat group Sequences (hook, then body; they abut, no overlap), and the shared
// hook overlay (frame 0 until the body's first shot). There are no group-edge blur breaks: the hook hands off into
// the body's first card (the hook builder shrinks its objects onto it, branching on bodyOf(useVariant()); the body's
// frame 0 shows the card). A builder who wants a blur break inside its own group uses <CrossBreak> from crossBreak.tsx.
//
// Voice: staticFile("ptp08/vo/<variant>.wav") unless `mute`. A provisional timeline (storyboard frames, no voice
// yet) always renders silent, so stills and previews never need the voice file; a real timeline always plays it.
// ===========================================================================

export type Ep08Props = { variant: Variant; mute: boolean };

const GROUPS: Record<GroupId, React.FC> = { HA, HB, HC, BodyA, BodyB, BodyC };
/** the component for one of a variant's two timeline groups: its hook (H + hookOf) or its body (Body + bodyOf) */
const beatFor = (v: Variant, g: GroupId): React.FC => GROUPS[(g.startsWith("Body") ? `Body${bodyOf(v)}` : `H${hookOf(v)}`) as GroupId];

export const GithubEp08: React.FC<Ep08Props> = ({ variant, mute }) => {
  const tl = TIMELINE[variant] ?? TIMELINE.A;
  return (
    <VariantCtx.Provider value={tl.variant}>
      {/* 5% side padding on everything the cameras draw (Victor 2026-10-31, ep04), grounds stay full-bleed */}
      <PadCtx.Provider value={0.9}>
        <AbsoluteFill style={{ backgroundColor: "#F4F3F2" }}>
          {mute || tl.provisional ? null : <Audio src={staticFile(tl.vo)} />}
          <CrtPass>
            {tl.groups.map((g) => {
              const Beat = beatFor(tl.variant, g.id);
              return (
                <Sequence key={g.id} from={g.start} durationInFrames={g.end - g.start} name={g.id}>
                  <GroupStartCtx.Provider value={g.start}>
                    <Beat />
                  </GroupStartCtx.Provider>
                </Sequence>
              );
            })}
            <Sequence durationInFrames={tl.bodyStart} name="HookOverlay">
              <HookOverlay len={tl.bodyStart} />
            </Sequence>
          </CrtPass>
        </AbsoluteFill>
      </PadCtx.Provider>
    </VariantCtx.Provider>
  );
};
